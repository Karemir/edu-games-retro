// Build-time tool (run through the browser runner): packs the frames of the garden reward symbols (itm_1..itm_21) into one
// lossy-WebP sprite sheet each (achievements/Assets/items/itm_N.webp) and writes the frame table
// achievements/src/Achievements/ItemSheets.ts.
//
// Source of the frames (one-off, third-party build tool, JPEXS Free Flash Decompiler 26.4.0, https://github.com/jindrapetrik/jpexs-decompiler):
//   unzip lib/ogrod_popr_01.swc library.swf  (from "flash originals/EduAchievements/lib")
//   java -jar ffdec-cli.jar -format sprite:png -zoom 2 -export sprite <out> library.swf
//   copy <out>/DefineSprite_*_itm_N/*.png to scripts/tools/.cache/itm/itm_N/
// then: node scripts/browser-test.mjs scripts/tools/make-garden-items.mjs --headless
import { readdirSync, writeFileSync } from "node:fs";

const ZOOM = 2; // the frames were exported at 2x
const MAX_SHEET = 8192;

export default async ({ ev, goto }) => {
	const names = readdirSync("scripts/tools/.cache/itm").sort((a, b) => Number(a.slice(4)) - Number(b.slice(4)));
	await goto("/");
	const table = {};
	for (const name of names) {
		const frames = readdirSync(`scripts/tools/.cache/itm/${name}`).length;
		const result = JSON.parse(await ev(`(async () => {
			const load = i => new Promise((res, rej) => { const im = new Image(); im.onload = () => res(im); im.onerror = rej; im.src = '/scripts/tools/.cache/itm/${name}/' + i + '.png'; });
			const first = await load(1);
			const w = first.width, h = first.height, n = ${frames};
			const cols = Math.max(1, Math.min(n, Math.floor(${MAX_SHEET} / w)));
			const rows = Math.ceil(n / cols);
			const c = document.createElement('canvas'); c.width = cols * w; c.height = rows * h;
			const x = c.getContext('2d');
			for (let i = 1; i <= n; i++) { const im = i == 1 ? first : await load(i); x.drawImage(im, ((i - 1) % cols) * w, Math.floor((i - 1) / cols) * h); }
			const blob = await new Promise(r => c.toBlob(r, 'image/webp', 0.85));
			const buf = new Uint8Array(await blob.arrayBuffer());
			let s = ''; for (let k = 0; k < buf.length; k += 0x8000) s += String.fromCharCode.apply(null, buf.subarray(k, k + 0x8000));
			return JSON.stringify({ w, h, cols, rows, bytes: buf.length, b64: btoa(s) });
		})()`));
		writeFileSync(`achievements/Assets/items/${name}.webp`, Buffer.from(result.b64, "base64"));
		table[name] = { frames, w: result.w, h: result.h, cols: result.cols };
		console.log(name, `${frames} frames ${result.w}x${result.h} -> ${(result.bytes / 1024).toFixed(0)} KB`);
	}
	const lines = names.map(n => `\t${n}: { frames: ${table[n].frames}, w: ${table[n].w}, h: ${table[n].h}, cols: ${table[n].cols} },`);
	writeFileSync("achievements/src/Achievements/ItemSheets.ts", `// Generated by scripts/tools/make-garden-items.mjs, do not edit.
// Frame tables of the garden reward sprite sheets (frames are ${ZOOM}x the symbol size).
export const ITEM_SHEET_ZOOM = ${ZOOM};

export const ITEM_SHEETS: { [name: string]: { frames: number; w: number; h: number; cols: number } } = {
${lines.join("\n")}
};
`);
};
