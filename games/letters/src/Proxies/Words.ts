	public GetWords(letterCount: number): any[] {
		var keys: any[] = [];
		for (var key in this.sounds) {
			if(key.length == letterCount){
				keys.push(key);
			}
		}
		return keys;
	}
	
	public PlaySound(word: string): void {
		var sound: Sounds = AppFacade.GetInstance().retrieveProxy(Sounds.NAME) as Sounds;
		if(sound.soundsEnabled){
			this.sounds[word].play();
		}
	}
	
